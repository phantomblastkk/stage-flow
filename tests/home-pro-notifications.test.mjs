test("home only features publicly verified singers without leaking admin or personal fields",()=>{
 assert.match(publicSql,/create or replace function public\.stage_public_verified_singers/);
 assert.match(publicSql,/join public\.profiles p on p\.id=v\.target_id/);
 assert.match(publicSql,/v\.kind='singer'/);
 assert.match(publicSql,/p\.is_singer=true and p\.is_artist=true/);
 assert.match(publicSql,/p\.is_public=true/);
 assert.match(publicSql,/p\.username ~ '\^\[a-z0-9-\]\{3,30\}\$'/);
 assert.match(publicSql,/grant execute on function public\.stage_public_verified_singers\(integer\) to anon,authenticated/);
 assert.doesNotMatch(publicSql,/raw_user_meta_data|auth\.users|service_role|SELECT \*/i);
 assert.match(home,/HomePartnerVenues\/>/);
 assert.match(home,/HomeVerifiedArtists\/>/);
 assert.ok(home.indexOf("<HomePartnerVenues/>")<home.indexOf("<HomeVerifiedArtists/>"));
 assert.match(verified,/stage_public_verified_singers/);
 assert.match(verified,/StageVerifiedBadge compact/);
 assert.match(verified,/stage-artist-public/);
 assert.match(verified,/\/\^\[0-9a-f-\]\{36\}/);
 assert.doesNotMatch(verified,/\.from\("profiles"\)|\.from\("stage_admin_verifications"\)/);
});
