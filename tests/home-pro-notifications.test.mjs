test("pro courtesy notifications are transaction-bound, private and revive on re-grant",()=>{
 assert.match(notificationSql,/source_type in \('invitation','proposal','conversation','operations','account'\)/);
 assert.match(notificationSql,/'pro_courtesy_granted','pro_courtesy_revoked'/);
 assert.match(notificationSql,/after insert or delete on public\.stage_pro_site_access/);
 assert.match(notificationSql,/v_owner:=new\.owner_id/);
 assert.match(notificationSql,/v_owner:=old\.owner_id/);
 assert.match(notificationSql,/on conflict\(recipient_id,source_type,source_id,event_code\)/);
 assert.match(notificationSql,/read_at=null/);
 assert.match(notificationSql,/from public\.stage_pro_site_access a/);
 assert.doesNotMatch(notificationSql,/grant (select|insert|update|delete) on public\.stage_internal_notifications/i);
 assert.doesNotMatch(notificationSql,/update public\.profiles|update public\.subscription|net\.http|service_role/i);
 assert.match(bell,/source_type==="account"/);
 assert.match(bell,/pro_courtesy_granted/);
 assert.match(bell,/stage_notifications_unread_count/);
 assert.match(bell,/setUnread\(count => count === null/);
 assert.match(bell,/p_ids: \[item\.id\], p_all: false/);
 assert.match(bell,/visibilitychange/);
 assert.match(bell,/window\.addEventListener\("focus"/);
 assert.match(bell,/\/meu-perfil-artistico\?aba=pro/);
 assert.match(inbox,/pro_courtesy_granted:"Cortesia Pro recebida"/);
 assert.match(inbox,/setUnread\(count=>Math\.max\(0,count-1\)\)/);
 assert.match(inbox,/\/minha-conta\?aba=cantor/);
 assert.doesNotMatch(bell,/\.from\("stage_internal_notifications"\)/);
});
