-- Execute no SQL Editor do Supabase uma única vez.

create table if not exists public.cities (
  id bigint generated by default as identity primary key,
  name text not null,
  state_code text not null default 'SP',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (name, state_code)
);
create table if not exists public.venues (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  city_id bigint references public.cities(id) on delete set null,
  address text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create index if not exists cities_search_idx on public.cities (lower(name)) where active = true;
create index if not exists venues_name_search_idx on public.venues (lower(name)) where active = true;
create index if not exists venues_city_idx on public.venues (city_id) where active = true;
alter table public.cities enable row level security;
alter table public.venues enable row level security;
drop policy if exists "Anyone can view active cities" on public.cities;
create policy "Anyone can view active cities" on public.cities for select using (active = true);
drop policy if exists "Anyone can view active venues" on public.venues;
create policy "Anyone can view active venues" on public.venues for select using (active = true);
